CREATE TABLE daily_tasks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_day DATE NOT NULL, track VARCHAR(255) NOT NULL, title VARCHAR(500) NOT NULL,
 description VARCHAR(2500), minutes INTEGER NOT NULL, done BOOLEAN NOT NULL DEFAULT FALSE,
 custom BOOLEAN NOT NULL DEFAULT FALSE, note VARCHAR(1200), completed_at TIMESTAMP,
 seed_key VARCHAR(80) UNIQUE, actual_minutes INTEGER NOT NULL DEFAULT 0,
 priority VARCHAR(10) DEFAULT 'Normal', deliverable_link VARCHAR(1200) DEFAULT '',
 CHECK (minutes BETWEEN 5 AND 840), CHECK (actual_minutes BETWEEN 0 AND 840)
);
CREATE INDEX idx_daily_tasks_date ON daily_tasks(task_day);
CREATE TABLE daily_journals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, journal_day DATE NOT NULL UNIQUE,
 energy INTEGER NOT NULL DEFAULT 3, wins VARCHAR(5000), blockers VARCHAR(5000), tomorrow VARCHAR(5000),
 actual_minutes INTEGER NOT NULL DEFAULT 0, CHECK (energy BETWEEN 1 AND 5), CHECK (actual_minutes BETWEEN 0 AND 1440)
);
CREATE TABLE dsa_problem (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, solved_on DATE,
 name VARCHAR(255) NOT NULL, topic VARCHAR(255), difficulty VARCHAR(255), status VARCHAR(255),
 minutes INTEGER, revision_on DATE, link VARCHAR(1200), insight VARCHAR(2000), CHECK (minutes BETWEEN 0 AND 1000)
);
CREATE INDEX idx_dsa_solved ON dsa_problem(solved_on);
CREATE TABLE job_application (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company VARCHAR(255) NOT NULL, role VARCHAR(255) NOT NULL,
 stage VARCHAR(255), applied_on DATE, deadline DATE, interview_on DATE, follow_up_on DATE,
 salary VARCHAR(255), link VARCHAR(1200), notes VARCHAR(2000)
);
CREATE INDEX idx_jobs_deadline ON job_application(deadline);
CREATE INDEX idx_jobs_interview ON job_application(interview_on);
